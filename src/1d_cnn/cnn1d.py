import os
import numpy as np
import pandas as pd
import kagglehub
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import classification_report, confusion_matrix
from tensorflow import keras
from tensorflow.keras import layers

keras.utils.set_random_seed(42)

# ---------- 1. Load ----------
path = kagglehub.dataset_download("hassan06/nslkdd")
cols = ["duration","protocol_type","service","flag","src_bytes","dst_bytes","land",
"wrong_fragment","urgent","hot","num_failed_logins","logged_in","num_compromised",
"root_shell","su_attempted","num_root","num_file_creations","num_shells",
"num_access_files","num_outbound_cmds","is_host_login","is_guest_login","count",
"srv_count","serror_rate","srv_serror_rate","rerror_rate","srv_rerror_rate",
"same_srv_rate","diff_srv_rate","srv_diff_host_rate","dst_host_count",
"dst_host_srv_count","dst_host_same_srv_rate","dst_host_diff_srv_rate",
"dst_host_same_src_port_rate","dst_host_srv_diff_host_rate","dst_host_serror_rate",
"dst_host_srv_serror_rate","dst_host_rerror_rate","dst_host_srv_rerror_rate",
"label","difficulty"]

train = pd.read_csv(os.path.join(path, "KDDTrain+.txt"), names=cols)
test  = pd.read_csv(os.path.join(path, "KDDTest+.txt"),  names=cols)
df = pd.concat([train, test], ignore_index=True).drop(columns="difficulty")
print("combined:", df.shape)

# ---------- 2. Labels + encoding ----------
y = (df.pop("label") != "normal").astype(int).values
X = pd.get_dummies(df, columns=["protocol_type", "service", "flag"]).astype("float32").values
feature_names = pd.get_dummies(df, columns=["protocol_type", "service", "flag"]).columns.tolist()

# ---------- 3. Split 60 / 15 / 25 (stratified) ----------
X_tmp, X_test, y_tmp, y_test = train_test_split(
    X, y, test_size=0.25, stratify=y, random_state=42)
X_train, X_val, y_train, y_val = train_test_split(
    X_tmp, y_tmp, test_size=0.20, stratify=y_tmp, random_state=42)  # 0.15 / 0.75 = 0.20

scaler = MinMaxScaler().fit(X_train)             # fit on train only
X_train, X_val, X_test = [scaler.transform(a)[..., None] for a in (X_train, X_val, X_test)]
print("train/val/test:", len(X_train), len(X_val), len(X_test))

# ---------- 4. 1D CNN ----------
model = keras.Sequential([
    layers.Input(shape=X_train.shape[1:]),
    layers.Conv1D(64, 3, padding="same", activation="relu"),
    layers.BatchNormalization(),
    layers.MaxPooling1D(2),
    layers.Conv1D(128, 3, padding="same", activation="relu"),
    layers.BatchNormalization(),
    layers.MaxPooling1D(2),
    layers.Conv1D(128, 3, padding="same", activation="relu"),
    layers.GlobalMaxPooling1D(),
    layers.Dense(64, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(1, activation="sigmoid"),
])
model.compile(optimizer=keras.optimizers.Adam(learning_rate=1e-3, weight_decay=1e-4),
              loss="binary_crossentropy", metrics=["accuracy"])
model.summary()

# ---------- 5. Train (fixed 20 epochs, no early stopping) ----------
history = model.fit(X_train, y_train, validation_data=(X_val, y_val),
                    epochs=20, batch_size=256, verbose=2)

# ---------- 6. Evaluate ----------
pred = (model.predict(X_test, verbose=0) > 0.5).astype(int).ravel()
print(classification_report(y_test, pred, target_names=["normal", "attack"], digits=4))
print("confusion matrix:\n", confusion_matrix(y_test, pred))

