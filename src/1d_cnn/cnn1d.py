import os
import shap
import lime
import lime.lime_tabular
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

os.makedirs("results/1d_cnn", exist_ok=True)

# ---------- Feature names ----------
# must match the exact columns used to build X (same order, before .values)
feature_names = pd.get_dummies(df, columns=["protocol_type", "service", "flag"]).columns.tolist()

# ---------- SHAP ----------
np.random.seed(42)
background = X_train[np.random.choice(len(X_train), 100, replace=False)]
explainer = shap.GradientExplainer(model, background)

sample_idx = np.random.choice(len(X_test), 200, replace=False)
X_sample = X_test[sample_idx]
y_sample = y_test[sample_idx]

shap_values = explainer.shap_values(X_sample)
sv = np.array(shap_values).squeeze()      # (200, n_features)
X_flat = X_sample.squeeze(-1)             # (200, n_features)

# global explanation
shap.summary_plot(sv, X_flat, feature_names=feature_names, show=False)
plt.tight_layout()
plt.savefig("results/1d_cnn/shap_summary_nsl.png", dpi=150, bbox_inches="tight")
plt.close()

# baseline for force plot (GradientExplainer has no expected_value)
baseline = float(model.predict(background, verbose=0).mean())

# ---------- Pick samples: one correct, one misclassified (if any) ----------
preds = (model.predict(X_sample, verbose=0).ravel() > 0.5).astype(int)
correct_idx = np.where(preds == y_sample)[0]
wrong_idx = np.where(preds != y_sample)[0]

picks = [("correct", correct_idx[0])]
if len(wrong_idx) > 0:
    picks.append(("misclassified", wrong_idx[0]))

for tag, i in picks:
    print(f"[{tag}] sample {i} — predicted: {preds[i]}, true: {y_sample[i]}, "
          f"predicted prob: {model.predict(X_sample[i:i+1], verbose=0)[0][0]:.4f}")

    shap.force_plot(baseline, sv[i], X_flat[i],
                     feature_names=feature_names, matplotlib=True, show=False)
    plt.tight_layout()
    plt.savefig(f"results/1d_cnn/shap_force_{tag}_nsl.png", dpi=150, bbox_inches="tight")
    plt.close()

# ---------- LIME ----------
X_train_flat = X_train.squeeze(-1)

def predict_fn(x):
    x = x[..., None]
    prob = model.predict(x, verbose=0).ravel()
    return np.column_stack([1 - prob, prob])

lime_explainer = lime.lime_tabular.LimeTabularExplainer(
    X_train_flat, feature_names=feature_names,
    class_names=["normal", "attack"], mode="classification")

for tag, i in picks:
    exp = lime_explainer.explain_instance(X_flat[i], predict_fn, num_features=10)
    exp.save_to_file(f"results/1d_cnn/lime_{tag}_nsl.html")
    print(f"[{tag}] LIME:", exp.as_list())

