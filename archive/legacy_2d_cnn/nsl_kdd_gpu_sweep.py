"""Vectorized GPU sweep for the NSL-KDD 2D-CNN reproduction.

Each experiment trains 64 independently initialized replicas concurrently in
one CUDA process. Replica isolation is preserved with grouped convolutions:
group i owns its own weights and sees the split/shuffle generated by seed i.

The default matrix covers the material choices that the paper leaves open:

* per-replica batch size: 32, 64, 128
* the unexplained 36th input: NSL-KDD difficulty or one zero-padding value
* weight-decay semantics: decoupled AdamW or coupled Adam L2

All other architecture settings are fixed by the paper or mathematical
necessity. In particular, ceil-mode pooling implements same-padding because a
6x6 input cannot survive three valid 2x2 pools.
"""

from __future__ import annotations

import argparse
import json
import math
import time
from dataclasses import asdict, dataclass
from itertools import product
from pathlib import Path
from typing import Any, Iterable

import numpy as np
import pandas as pd

import nsl_kdd_2dcnn as base


DEFAULT_BATCH_SIZES = (32, 64, 128)
DEFAULT_FEATURE_MODES = ("difficulty", "zero_pad")
DEFAULT_OPTIMIZERS = ("adamw", "adam_l2")


@dataclass(frozen=True)
class SweepConfig:
    batch_size: int
    feature_mode: str
    optimizer: str

    @property
    def config_id(self) -> str:
        return f"batch{self.batch_size:03d}-{self.feature_mode}-{self.optimizer}"


@dataclass
class FeatureData:
    features: np.ndarray
    labels: np.ndarray
    metadata: dict[str, Any]


def experiment_matrix(
    batch_sizes: Iterable[int] = DEFAULT_BATCH_SIZES,
    feature_modes: Iterable[str] = DEFAULT_FEATURE_MODES,
    optimizers: Iterable[str] = DEFAULT_OPTIMIZERS,
) -> list[SweepConfig]:
    return [
        SweepConfig(batch, feature_mode, optimizer)
        for batch, feature_mode, optimizer in product(
            batch_sizes, feature_modes, optimizers
        )
    ]


def select_random_seeds(count: int, master_seed: int) -> list[int]:
    if count <= 0:
        raise ValueError("Seed count must be positive.")
    rng = np.random.default_rng(master_seed)
    values = rng.choice(np.arange(1, 2**31 - 1, dtype=np.int64), count, replace=False)
    return [int(value) for value in values]


def prepare_features(train_path: Path, feature_mode: str) -> FeatureData:
    frame = base.read_nsl_kdd(train_path)
    labels = base.map_attack_labels(frame["label"])

    if feature_mode == "difficulty":
        predictors = frame.drop(columns=["label"])
        note = "Retains NSL-KDD difficulty as the 36th model input."
    elif feature_mode == "zero_pad":
        predictors = frame.drop(columns=["label", "difficulty"])
        note = "Removes NSL-KDD difficulty and appends one zero-padding value."
    else:
        raise ValueError(f"Unknown feature mode: {feature_mode}")

    predictors = predictors.drop(columns=base.PAPER_DROPPED_FEATURES)
    category_maps = base.fit_category_maps(predictors)
    predictors = base.encode_categories(predictors, category_maps)
    minimum, maximum = base.fit_minmax(predictors)
    features = base.apply_minmax(predictors, minimum, maximum, clip=True)

    feature_names = predictors.columns.tolist()
    if feature_mode == "zero_pad":
        features = np.pad(features, ((0, 0), (0, 1)), constant_values=0.0)
        feature_names.append("__zero_padding__")
    if features.shape[1] != 36:
        raise AssertionError(f"Expected 36 model inputs, got {features.shape[1]}.")

    metadata = {
        "feature_mode": feature_mode,
        "feature_names": feature_names,
        "note": note,
        "paper_dropped_features": base.PAPER_DROPPED_FEATURES,
        "category_maps": category_maps,
        "minima": minimum.to_dict(),
        "maxima": maximum.to_dict(),
        "preprocessing_scope": "full KDDTrain+ before the paper's random split",
    }
    return FeatureData(
        features.reshape((-1, 1, 6, 6)).astype(np.float32, copy=False),
        labels,
        metadata,
    )


def build_seed_splits(
    labels: np.ndarray, seeds: list[int]
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    train_rows = []
    validation_rows = []
    test_rows = []
    for seed in seeds:
        train_idx, validation_idx, test_idx = base.stratified_partition(
            labels, (0.60, 0.15, 0.25), seed
        )
        train_rows.append(train_idx)
        validation_rows.append(validation_idx)
        test_rows.append(test_idx)
    return (
        np.stack(train_rows),
        np.stack(validation_rows),
        np.stack(test_rows),
    )


def _torch():
    try:
        import torch
    except (ImportError, OSError) as exc:
        raise SystemExit(
            "A working CUDA-enabled PyTorch environment is required. Run this "
            "script from your existing Python environment."
        ) from exc
    return torch


class VectorizedCNN:
    """Factory namespace used so the module remains importable without PyTorch."""

    @staticmethod
    def create(seeds: list[int], device: str):
        torch = _torch()
        nn = torch.nn
        functional = torch.nn.functional

        class _VectorizedCNN(nn.Module):
            def __init__(self) -> None:
                super().__init__()
                self.replicas = len(seeds)
                self.conv1_weight = nn.Parameter(torch.empty(self.replicas, 64, 1, 3, 3))
                self.conv1_bias = nn.Parameter(torch.empty(self.replicas, 64))
                self.conv2_weight = nn.Parameter(torch.empty(self.replicas, 32, 64, 3, 3))
                self.conv2_bias = nn.Parameter(torch.empty(self.replicas, 32))
                self.conv3_weight = nn.Parameter(torch.empty(self.replicas, 32, 32, 3, 3))
                self.conv3_bias = nn.Parameter(torch.empty(self.replicas, 32))
                self.dense_weight = nn.Parameter(torch.empty(self.replicas, 5, 32))
                self.dense_bias = nn.Parameter(torch.empty(self.replicas, 5))
                self._reset_parameters()

            @staticmethod
            def _initialize_layer(weight, bias, seed: int) -> None:
                generator = torch.Generator(device="cpu")
                generator.manual_seed(seed)
                nn.init.kaiming_uniform_(weight, a=math.sqrt(5), generator=generator)
                fan_in, _ = nn.init._calculate_fan_in_and_fan_out(weight)
                bound = 1.0 / math.sqrt(fan_in)
                nn.init.uniform_(bias, -bound, bound, generator=generator)

            def _reset_parameters(self) -> None:
                with torch.no_grad():
                    for replica, seed in enumerate(seeds):
                        self._initialize_layer(
                            self.conv1_weight[replica], self.conv1_bias[replica], seed + 11
                        )
                        self._initialize_layer(
                            self.conv2_weight[replica], self.conv2_bias[replica], seed + 23
                        )
                        self._initialize_layer(
                            self.conv3_weight[replica], self.conv3_bias[replica], seed + 37
                        )
                        self._initialize_layer(
                            self.dense_weight[replica], self.dense_bias[replica], seed + 53
                        )

            def forward(self, inputs):
                # inputs: [replica, batch, channel=1, height=6, width=6]
                replica_count, batch_size, _, height, width = inputs.shape
                if replica_count != self.replicas:
                    raise ValueError(
                        f"Expected {self.replicas} replicas, got {replica_count}."
                    )
                values = inputs.permute(1, 0, 2, 3, 4).reshape(
                    batch_size, self.replicas, height, width
                )
                values = functional.conv2d(
                    values,
                    self.conv1_weight.reshape(self.replicas * 64, 1, 3, 3),
                    self.conv1_bias.reshape(-1),
                    padding=1,
                    groups=self.replicas,
                )
                values = functional.max_pool2d(
                    functional.relu(values), kernel_size=2, stride=2, ceil_mode=True
                )
                values = functional.conv2d(
                    values,
                    self.conv2_weight.reshape(self.replicas * 32, 64, 3, 3),
                    self.conv2_bias.reshape(-1),
                    padding=1,
                    groups=self.replicas,
                )
                values = functional.max_pool2d(
                    functional.relu(values), kernel_size=2, stride=2, ceil_mode=True
                )
                values = functional.conv2d(
                    values,
                    self.conv3_weight.reshape(self.replicas * 32, 32, 3, 3),
                    self.conv3_bias.reshape(-1),
                    padding=1,
                    groups=self.replicas,
                )
                values = functional.max_pool2d(
                    functional.relu(values), kernel_size=2, stride=2, ceil_mode=True
                )
                values = values.reshape(batch_size, self.replicas, 32).permute(1, 0, 2)
                return torch.einsum(
                    "sbi,soi->sbo", values, self.dense_weight
                ) + self.dense_bias[:, None, :]

        return _VectorizedCNN().to(device)


def evaluate(model, features, labels, indices, batch_size: int) -> dict[str, np.ndarray]:
    torch = _torch()
    functional = torch.nn.functional
    replicas, row_count = indices.shape
    loss_sum = torch.zeros(replicas, device=features.device, dtype=torch.float64)
    correct = torch.zeros(replicas, device=features.device, dtype=torch.int64)
    confusion = torch.zeros(replicas * 25, device=features.device, dtype=torch.int64)

    model.eval()
    with torch.inference_mode():
        for start in range(0, row_count, batch_size):
            batch_indices = indices[:, start : start + batch_size]
            batch_features = features[batch_indices]
            batch_labels = labels[batch_indices]
            with torch.autocast(device_type="cuda", dtype=torch.float16):
                logits = model(batch_features)
                losses = functional.cross_entropy(
                    logits.reshape(-1, 5),
                    batch_labels.reshape(-1),
                    reduction="none",
                ).reshape(replicas, -1)
            predictions = logits.argmax(dim=2)
            loss_sum += losses.double().sum(dim=1)
            correct += (predictions == batch_labels).sum(dim=1)
            offsets = torch.arange(replicas, device=features.device)[:, None] * 25
            codes = offsets + batch_labels * 5 + predictions
            confusion += torch.bincount(codes.reshape(-1), minlength=replicas * 25)

    return {
        "loss": (loss_sum / row_count).cpu().numpy(),
        "accuracy": (correct.double() / row_count).cpu().numpy(),
        "confusion": confusion.reshape(replicas, 5, 5).cpu().numpy(),
    }


def metrics_from_confusions(confusions: np.ndarray) -> dict[str, np.ndarray]:
    true_positive = np.diagonal(confusions, axis1=1, axis2=2).astype(np.float64)
    predicted = confusions.sum(axis=1)
    actual = confusions.sum(axis=2)
    precision = np.divide(
        true_positive,
        predicted,
        out=np.zeros_like(true_positive),
        where=predicted != 0,
    )
    recall = np.divide(
        true_positive,
        actual,
        out=np.zeros_like(true_positive),
        where=actual != 0,
    )
    f1 = np.divide(
        2 * precision * recall,
        precision + recall,
        out=np.zeros_like(precision),
        where=(precision + recall) != 0,
    )
    return {
        "macro_precision": precision.mean(axis=1),
        "macro_recall": recall.mean(axis=1),
        "macro_f1": f1.mean(axis=1),
        **{
            metric_name: values[:, class_id]
            for class_id, class_name in enumerate(base.CLASS_NAMES)
            for metric_name, values in (
                (f"{class_name.lower()}_precision", precision),
                (f"{class_name.lower()}_recall", recall),
                (f"{class_name.lower()}_f1", f1),
            )
        },
    }


def train_configuration(
    config: SweepConfig,
    data: FeatureData,
    seeds: list[int],
    split_indices: tuple[np.ndarray, np.ndarray, np.ndarray],
    output_dir: Path,
    *,
    epochs: int,
    learning_rate: float,
    weight_decay: float,
    device: str,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    torch = _torch()
    functional = torch.nn.functional
    config_dir = output_dir / config.config_id
    config_dir.mkdir(parents=True, exist_ok=True)
    result_path = config_dir / "seed_results.csv"
    history_path = config_dir / "history.csv"
    summary_path = config_dir / "summary.json"
    checkpoint_path = config_dir / "checkpoint.pt"
    if (
        result_path.exists()
        and history_path.exists()
        and summary_path.exists()
        and checkpoint_path.exists()
    ):
        print(f"Skipping completed configuration {config.config_id}")
        return (
            pd.read_csv(result_path),
            pd.read_csv(history_path),
            json.loads(summary_path.read_text(encoding="utf-8")),
        )

    train_np, validation_np, test_np = split_indices
    features = torch.as_tensor(data.features, device=device)
    labels = torch.as_tensor(data.labels, device=device, dtype=torch.long)
    validation_indices = torch.as_tensor(validation_np, device=device, dtype=torch.long)
    test_indices = torch.as_tensor(test_np, device=device, dtype=torch.long)

    model = VectorizedCNN.create(seeds, device)
    optimizer_class = torch.optim.AdamW if config.optimizer == "adamw" else torch.optim.Adam
    optimizer = optimizer_class(
        model.parameters(), lr=learning_rate, weight_decay=weight_decay
    )
    scaler = torch.amp.GradScaler("cuda")
    shuffle_rngs = [np.random.default_rng(seed + 1009) for seed in seeds]
    history_rows: list[dict[str, Any]] = []
    started = time.perf_counter()

    for epoch in range(1, epochs + 1):
        shuffled_np = np.stack(
            [rng.permutation(row) for rng, row in zip(shuffle_rngs, train_np)]
        )
        shuffled = torch.as_tensor(shuffled_np, device=device, dtype=torch.long)
        train_loss_sum = torch.zeros(len(seeds), device=device, dtype=torch.float64)
        train_correct = torch.zeros(len(seeds), device=device, dtype=torch.int64)
        model.train()

        for start in range(0, shuffled.shape[1], config.batch_size):
            batch_indices = shuffled[:, start : start + config.batch_size]
            batch_features = features[batch_indices]
            batch_labels = labels[batch_indices]
            optimizer.zero_grad(set_to_none=True)
            with torch.autocast(device_type="cuda", dtype=torch.float16):
                logits = model(batch_features)
                per_item_loss = functional.cross_entropy(
                    logits.reshape(-1, 5),
                    batch_labels.reshape(-1),
                    reduction="none",
                ).reshape(len(seeds), -1)
                per_replica_loss = per_item_loss.mean(dim=1)
                # Sum, not mean: each replica receives the same gradient magnitude
                # it would receive in an isolated optimizer/model process.
                loss = per_replica_loss.sum()
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
            train_loss_sum += per_item_loss.detach().double().sum(dim=1)
            train_correct += (logits.detach().argmax(dim=2) == batch_labels).sum(dim=1)

        validation = evaluate(
            model, features, labels, validation_indices, config.batch_size
        )
        train_losses = (train_loss_sum / shuffled.shape[1]).cpu().numpy()
        train_accuracies = (train_correct.double() / shuffled.shape[1]).cpu().numpy()
        for replica, seed in enumerate(seeds):
            history_rows.append(
                {
                    "config_id": config.config_id,
                    "seed": seed,
                    "epoch": epoch,
                    "train_loss": float(train_losses[replica]),
                    "train_accuracy": float(train_accuracies[replica]),
                    "validation_loss": float(validation["loss"][replica]),
                    "validation_accuracy": float(validation["accuracy"][replica]),
                }
            )
        print(
            f"{config.config_id} epoch {epoch:02d}/{epochs}: "
            f"train_acc={train_accuracies.mean():.4f}, "
            f"val_acc={validation['accuracy'].mean():.4f}"
        )

    test = evaluate(model, features, labels, test_indices, config.batch_size)
    test_metrics = metrics_from_confusions(test["confusion"])
    history = pd.DataFrame(history_rows)
    final_validation = history[history["epoch"] == epochs].reset_index(drop=True)
    results = pd.DataFrame(
        {
            "config_id": config.config_id,
            "batch_size": config.batch_size,
            "feature_mode": config.feature_mode,
            "optimizer": config.optimizer,
            "seed": seeds,
            "validation_accuracy": final_validation["validation_accuracy"],
            "validation_loss": final_validation["validation_loss"],
            "test_accuracy": test["accuracy"],
            "test_loss": test["loss"],
            **test_metrics,
        }
    )
    elapsed = time.perf_counter() - started
    mean_accuracy = float(results["test_accuracy"].mean())
    std_accuracy = float(results["test_accuracy"].std(ddof=1))
    summary = {
        "config": asdict(config),
        "replicas": len(seeds),
        "epochs": epochs,
        "learning_rate": learning_rate,
        "weight_decay": weight_decay,
        "elapsed_seconds": elapsed,
        "test_accuracy_mean": mean_accuracy,
        "test_accuracy_std": std_accuracy,
        "test_accuracy_95ci_half_width": 1.96 * std_accuracy / math.sqrt(len(seeds)),
        "test_accuracy_min": float(results["test_accuracy"].min()),
        "test_accuracy_max": float(results["test_accuracy"].max()),
        "concurrency": (
            f"{len(seeds)} independent replicas executed together using grouped CUDA convolutions"
        ),
    }

    results.to_csv(result_path, index=False)
    history.to_csv(history_path, index=False)
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    torch.save(
        {
            "config": asdict(config),
            "seeds": seeds,
            "model_state_dict": model.state_dict(),
            "feature_metadata": data.metadata,
        },
        checkpoint_path,
    )
    del model, optimizer, scaler, features, labels
    torch.cuda.empty_cache()
    return results, history, summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Train 64 NSL-KDD 2D-CNN replicas concurrently on CUDA."
    )
    parser.add_argument("--data-dir", type=Path, default=Path("Datasets/NSL-KDD"))
    parser.add_argument(
        "--output-dir", type=Path, default=Path("outputs/nsl_kdd_gpu_sweep")
    )
    parser.add_argument("--replicas", type=int, default=64)
    parser.add_argument("--master-seed", type=int, default=20260908)
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--learning-rate", type=float, default=0.001)
    parser.add_argument("--weight-decay", type=float, default=0.0001)
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=list(DEFAULT_BATCH_SIZES))
    parser.add_argument(
        "--feature-modes", nargs="+", choices=DEFAULT_FEATURE_MODES, default=list(DEFAULT_FEATURE_MODES)
    )
    parser.add_argument(
        "--optimizers", nargs="+", choices=DEFAULT_OPTIMIZERS, default=list(DEFAULT_OPTIMIZERS)
    )
    parser.add_argument(
        "--config-limit",
        type=int,
        default=None,
        help="Run only the first N configurations; intended for smoke tests.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    torch = _torch()
    if not torch.cuda.is_available():
        raise SystemExit("CUDA is required; no CUDA-capable PyTorch device was detected.")
    if args.replicas <= 0 or args.epochs <= 0:
        raise ValueError("--replicas and --epochs must be positive.")
    if any(batch <= 0 for batch in args.batch_sizes):
        raise ValueError("All batch sizes must be positive.")

    device = "cuda:0"
    torch.backends.cudnn.benchmark = True
    seeds = select_random_seeds(args.replicas, args.master_seed)
    configs = experiment_matrix(args.batch_sizes, args.feature_modes, args.optimizers)
    if args.config_limit is not None:
        configs = configs[: args.config_limit]
    args.output_dir.mkdir(parents=True, exist_ok=True)

    manifest = {
        "gpu": torch.cuda.get_device_name(0),
        "torch_version": torch.__version__,
        "cuda_runtime": torch.version.cuda,
        "master_seed": args.master_seed,
        "seeds": seeds,
        "replicas_per_configuration": args.replicas,
        "epochs": args.epochs,
        "learning_rate": args.learning_rate,
        "weight_decay": args.weight_decay,
        "configurations": [asdict(config) | {"config_id": config.config_id} for config in configs],
    }
    (args.output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    pd.DataFrame({"replica": range(args.replicas), "seed": seeds}).to_csv(
        args.output_dir / "seeds.csv", index=False
    )
    print(
        f"GPU: {manifest['gpu']} | PyTorch {manifest['torch_version']} | "
        f"CUDA {manifest['cuda_runtime']}"
    )
    print(
        f"Running {len(configs)} configurations x {args.replicas} concurrent replicas "
        f"x {args.epochs} epochs"
    )

    feature_cache = {
        mode: prepare_features(args.data_dir / "KDDTrain+.txt", mode)
        for mode in set(config.feature_mode for config in configs)
    }
    split_indices = build_seed_splits(
        next(iter(feature_cache.values())).labels, seeds
    )
    all_results = []
    all_histories = []
    summaries = []
    for config in configs:
        results, history, summary = train_configuration(
            config,
            feature_cache[config.feature_mode],
            seeds,
            split_indices,
            args.output_dir,
            epochs=args.epochs,
            learning_rate=args.learning_rate,
            weight_decay=args.weight_decay,
            device=device,
        )
        all_results.append(results)
        all_histories.append(history)
        summaries.append(summary)
        pd.concat(all_results, ignore_index=True).to_csv(
            args.output_dir / "all_seed_results.csv", index=False
        )
        pd.concat(all_histories, ignore_index=True).to_csv(
            args.output_dir / "all_histories.csv", index=False
        )
        pd.DataFrame(summaries).to_json(
            args.output_dir / "configuration_summary.json", orient="records", indent=2
        )

    summary_frame = pd.DataFrame(
        [
            {
                **summary["config"],
                "config_id": config.config_id,
                "test_accuracy_mean": summary["test_accuracy_mean"],
                "test_accuracy_std": summary["test_accuracy_std"],
                "test_accuracy_95ci_half_width": summary[
                    "test_accuracy_95ci_half_width"
                ],
                "test_accuracy_min": summary["test_accuracy_min"],
                "test_accuracy_max": summary["test_accuracy_max"],
                "elapsed_seconds": summary["elapsed_seconds"],
            }
            for config, summary in zip(configs, summaries)
        ]
    ).sort_values("test_accuracy_mean", ascending=False)
    summary_frame.to_csv(args.output_dir / "configuration_summary.csv", index=False)
    print("Sweep complete. Best configurations:")
    print(summary_frame.head(12).to_string(index=False))


if __name__ == "__main__":
    main()
